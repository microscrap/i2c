<?php

namespace Microscrap\Bindings\I2C\Enums;

enum I2CFuncFlag: int
{
    case I2C_FUNC = 0x00000001;
    case TENBIT_ADDR = 0x00000002;
    case PROTOCOL_MANGLING = 0x00000004;
    case SMBUS_PEC = 0x00000008;
    case NOSTART = 0x00000010;
    case SLAVE = 0x00000020;

    case SMBUS_BLOCK_PROC_CALL = 0x00008000;
    case SMBUS_QUICK = 0x00010000;
    case SMBUS_READ_BYTE = 0x00020000;
    case SMBUS_WRITE_BYTE = 0x00040000;
    case SMBUS_READ_BYTE_DATA = 0x00080000;
    case SMBUS_WRITE_BYTE_DATA = 0x00100000;
    case SMBUS_READ_WORD_DATA = 0x00200000;
    case SMBUS_WRITE_WORD_DATA = 0x00400000;
    case SMBUS_PROC_CALL = 0x00800000;
    case SMBUS_READ_BLOCK_DATA = 0x01000000;
    case SMBUS_WRITE_BLOCK_DATA = 0x02000000;
    case SMBUS_READ_I2C_BLOCK = 0x04000000;
    case SMBUS_WRITE_I2C_BLOCK = 0x08000000;
    case SMBUS_HOST_NOTIFY = 0x10000000;

    case SMBUS_BYTE = 0x00060000;
    case SMBUS_BYTE_DATA = 0x00180000;
    case SMBUS_WORD_DATA = 0x00600000;
    case SMBUS_BLOCK_DATA = 0x03000000;
    case SMBUS_I2C_BLOCK = 0x0C000000;

    // SMBUS_EMUL: capabilities emulatable in software by i2c-core
    case SMBUS_EMUL = 0x0EFF0008;
    // SMBUS_EMUL_ALL: SMBUS_EMUL + READ_BLOCK_DATA + BLOCK_PROC_CALL
    case SMBUS_EMUL_ALL = 0x0FFF8008;
}
